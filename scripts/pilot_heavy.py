CHECKER = r'''"""Independent artifact checks. Do not edit this file to pass a trial."""
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys
import xml.etree.ElementTree as ET
from tools.png_probe import inspect_png

root = Path(__file__).resolve().parent
scenario = json.loads((root / 'brief.json').read_text())['scenario']
checks = []
def check(name, passed, detail=''):
    checks.append(dict(name=name, passed=bool(passed), detail=detail))

names = ['before', 'after'] if scenario == 'revision-3d' else ['hero', 'front']
for name in names:
    path = root / 'outputs' / (name + '.png')
    try:
        body = path.read_bytes()
        width, height, depth, color = struct.unpack('>IIBB', body[16:26])
        check(name + '_png', body[:8] == b'\x89PNG\r\n\x1a\n' and width == 960 and height == 720 and depth == 8 and color == 6 and len(body) > 10000,
              f'{width}x{height}, depth={depth}, color={color}, bytes={len(body)}')
        info = inspect_png(body)
        check(name + '_alpha', info['alpha_min'] < 0.1 and info['alpha_max'] > 0.9, str(info))
    except (OSError, ValueError, struct.error, subprocess.SubprocessError) as error:
        check(name + '_png', False, str(error))

art = root / ('artwork/front.v2.svg' if scenario == 'revision-3d' else 'artwork/front.svg')
try:
    svg = ET.fromstring(art.read_text(encoding='utf-8'))
    text = ' '.join(svg.itertext())
    for required in ('RIMBA', 'TEH MELATI', '100 g' if scenario == 'revision-3d' else '80 g'):
        check('label_' + required, required in text)
    check('no_svg_script', not any(node.tag.split('}')[-1] in ('script', 'foreignObject') for node in svg.iter()))
    if scenario == 'revision-3d':
        check('refill_badge', 'REFILL' in text)
        expected = json.loads((root / 'brief.json').read_text())['original_artwork_sha256']
        check('v1_preserved', hashlib.sha256((root / 'artwork/front.svg').read_bytes()).hexdigest() == expected)
except (OSError, ValueError, ET.ParseError) as error:
    check('artwork', False, str(error))

for name in names:
    try:
        params = json.loads((root / 'configs' / (name + '.json')).read_text())
        check(name + '_dimensions', params.get('size_cm') == [12, 18, 6])
        check(name + '_render_settings', params.get('res') == [960, 720] and params.get('engine') == 'cycles' and params.get('fit') in ('contain', 'auto'))
    except (OSError, ValueError) as error:
        check(name + '_config', False, str(error))

if scenario == 'pipeline-repair':
    result = subprocess.run([sys.executable, '-m', 'unittest', '-v', 'test_pipeline'], cwd=root, capture_output=True, text=True, timeout=45)
    check('pipeline_regression', result.returncode == 0, (result.stdout + result.stderr)[-2000:])
check('delivery_manifest', (root / 'delivery.json').is_file())
check('handoff', (root / 'HANDOFF.md').is_file())
out = root / 'outputs/checks.json'
out.parent.mkdir(exist_ok=True)
result = {'scenario': scenario, 'passed': all(row['passed'] for row in checks), 'checks': checks}
out.write_text(json.dumps(result, indent=2), encoding='utf-8')
print(json.dumps(result))
sys.exit(0 if result['passed'] else 1)
'''

