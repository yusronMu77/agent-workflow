def scenarios():
    result = {}
    for scenario in ('packaging-3d', 'revision-3d', 'pipeline-repair'):
        spec = {'scenario': scenario, 'size_cm': [12, 18, 6], 'resolution': [960, 720]}
        files = {'check_delivery.py': CHECKER}
        if scenario == 'packaging-3d':
            task = ('Design premium jasmine tea packaging RIMBA. Palette deep teal #0f4c45, gold #e7b966, white. '
                    'Front text exactly RIMBA / TEH MELATI / 80 g; editable SVG at artwork/front.svg. '
                    'Create distinct side artwork with text SEDUH 3 MENIT and map it to the right face. '
                    'Render outputs/hero.png three-quarter studio and outputs/front.png front flat; configs/hero.json and configs/front.json. '
                    'Prioritize clear hierarchy, generous margins and correct front/right label orientation.\n')
        elif scenario == 'revision-3d':
            files['artwork/front.svg'] = FRONT
            spec['original_artwork_sha256'] = hashlib.sha256(FRONT.encode()).hexdigest()
            task = ('Revise the supplied tea package for a refill variant. Preserve artwork/front.svg byte-for-byte. '
                    'Create artwork/front.v2.svg retaining brand, product and palette, change 80 g to 100 g and add a visible REFILL badge. '
                    'Render outputs/before.png from original and outputs/after.png from v2, both three-quarter studio, same framing/material/light. '
                    'Use configs/before.json and configs/after.json. Document the change and compare views.\n')
        else:
            files['artwork/front.svg'] = FRONT
            files['pipeline.py'] = PIPELINE
            files['test_pipeline.py'] = PIPELINE_TESTS
            broken = {'size_cm': [12, 18, 6], 'out': '../outputs/hero.jpg', 'res': [960, 720],
                      'engine': 'cycles', 'samples': 24, 'artwork': {'front': '../artwork/FRONT-missing.svg'},
                      'transparent': True, 'fit': 'stretch'}
            files['configs/hero.json'] = json.dumps(broken, indent=2)
            files['diagnostic.txt'] = 'PASS material cache\n' * 4000 + 'ERROR unknown key transparent; out must end .png; artwork.front file not found\n' + 'PASS geometry cache\n' * 2500
            task = ('Repair pipeline.py so renderer failures propagate and zero renderer exit without a valid output cannot be reported as success. '
                    'Fix configs/hero.json using diagnostics and renderer specification; preserve diagnostic.txt and run regression tests. '
                    'Render outputs/hero.png three-quarter studio and outputs/front.png front flat using configs/hero.json and configs/front.json. '
                    'Keep existing artwork; do not weaken tests. Save failed and successful check logs.\n')
        files['brief.json'] = json.dumps(spec, indent=2) + '\n'
        files['brief.md'] = '# Task\n\n' + task + '\n' + COMMON
        result[scenario] = {'prompt': task + '\n' + COMMON,
                            'rubric': 'Independent check_delivery.py passes; brief/tools/tests preserved; both renders reviewed for clipping, orientation and legibility. Workflow arm completes its task with captured evidence.',
                            'files': files}
    return result


